#!/usr/bin/env node
import fs from 'fs';
import path from 'path';
import readline from 'readline';
import { spawn } from 'child_process';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const backendRoot = path.resolve(__dirname, '..');
const envPath = path.join(backendRoot, '.env');
const lockPath = path.join(backendRoot, '.stack.lock');

function defaultFrontendPath() {
  if (process.env.FRONTEND_PATH) return path.resolve(process.env.FRONTEND_PATH);
  const candidates = [
    path.resolve(backendRoot, '..', 'jobAndEducation-Hub-Next-JS'),
    path.resolve(backendRoot, '..', 'jobAndEducation-Hub-Next-JS-Final_Branch'),
  ];
  return candidates.find((dir) => fs.existsSync(path.join(dir, 'package.json'))) || candidates[0];
}

function parseArgs() {
  const args = new Set(process.argv.slice(2));
  return {
    setupOnly: args.has('--setup-only'),
    reset: args.has('--reset-stack'),
    defaults: args.has('--defaults'),
  };
}

function question(rl, prompt, fallback = '') {
  return new Promise((resolve) => {
    const suffix = fallback ? ` [${fallback}]` : '';
    rl.question(`${prompt}${suffix}: `, (answer) => {
      resolve(String(answer || '').trim() || fallback);
    });
  });
}

async function yesNo(rl, prompt, defaultYes = true) {
  const def = defaultYes ? 'Y/n' : 'y/N';
  const answer = await question(rl, `${prompt} (${def})`);
  if (!answer) return defaultYes;
  return ['y', 'yes', '1', 'true'].includes(answer.toLowerCase());
}

function quoteEnv(value) {
  const str = String(value ?? '');
  if (/[\s#"'=]/.test(str)) return `"${str.replace(/"/g, '\\"')}"`;
  return str;
}

function writeEnvFile(filePath, values) {
  const lines = ['# Generated by scripts/stack.mjs — edit as needed', ''];
  for (const [key, value] of Object.entries(values)) {
    if (value === undefined || value === null) continue;
    lines.push(`${key}=${quoteEnv(value)}`);
  }
  fs.writeFileSync(filePath, `${lines.join('\n')}\n`, 'utf8');
}

function loadDotEnv(filePath) {
  if (!fs.existsSync(filePath)) return {};
  const out = {};
  for (const line of fs.readFileSync(filePath, 'utf8').split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const eq = trimmed.indexOf('=');
    if (eq === -1) continue;
    let val = trimmed.slice(eq + 1).trim();
    if ((val.startsWith('"') && val.endsWith('"')) || (val.startsWith("'") && val.endsWith("'"))) {
      val = val.slice(1, -1);
    }
    out[trimmed.slice(0, eq).trim()] = val;
  }
  return out;
}

function applyEnv(values) {
  for (const [key, value] of Object.entries(values)) {
    if (value === undefined || value === null) continue;
    process.env[key] = String(value);
  }
}

function run(cmd, args, opts = {}) {
  return new Promise((resolve, reject) => {
    const child = spawn(cmd, args, { stdio: 'inherit', shell: true, cwd: backendRoot, ...opts });
    child.on('exit', (code) => {
      if (code === 0) resolve();
      else reject(new Error(`${cmd} ${args.join(' ')} exited with code ${code}`));
    });
  });
}

function defaultCfg() {
  return {
    hosting: 'local',
    dbProvider: 'sqlite',
    databaseUrl: '',
    sqliteUrl: 'file:./dev.db',
    redisEnabled: false,
    redisUrl: 'redis://127.0.0.1:6379',
    searchEnabled: false,
    esUrl: '',
    jwtSecret: 'dev_secret_change_me',
    corsOrigin: '*',
    seed: true,
  };
}

async function wizard() {
  const rl = readline.createInterface({ input: process.stdin, output: process.stdout });
  console.log('\nJob Portal stack setup (first run)\n');
  console.log('SQLite / MySQL / PostgreSQL are alternative primary databases.');
  console.log('Redis and Elasticsearch are optional add-ons (forced off on Vercel).\n');

  const hostingRaw = (await question(rl, 'Hosting platform (local / vercel)', 'local')).toLowerCase();
  const hosting = hostingRaw === 'vercel' ? 'vercel' : 'local';
  const isVercel = hosting === 'vercel';

  let dbProvider = (await question(
    rl,
    'Primary database (sqlite / mysql / postgresql)',
    isVercel ? 'postgresql' : 'sqlite',
  )).toLowerCase();
  if (dbProvider === 'postgres') dbProvider = 'postgresql';
  if (!['sqlite', 'mysql', 'postgresql'].includes(dbProvider)) {
    console.log('Unknown database, defaulting to sqlite');
    dbProvider = 'sqlite';
  }

  let databaseUrl = '';
  let sqliteUrl = 'file:./dev.db';
  if (dbProvider === 'sqlite') {
    sqliteUrl = await question(rl, 'SQLite file URL', 'file:./dev.db');
    if (isVercel) {
      console.log('Warning: a local SQLite file will not persist on Vercel. Prefer Neon Postgres.');
    }
  } else if (dbProvider === 'mysql') {
    databaseUrl = await question(rl, 'DATABASE_URL', 'mysql://root:password@127.0.0.1:3306/job_portal');
  } else {
    databaseUrl = await question(rl, 'DATABASE_URL', 'postgresql://user:password@127.0.0.1:5432/job_portal');
  }

  let redisEnabled = false;
  let redisUrl = 'redis://127.0.0.1:6379';
  let searchEnabled = false;
  let esUrl = '';
  if (isVercel) {
    console.log('Vercel mode: Redis, Elasticsearch, Socket.IO, and queues are forced off by HOSTING_PLATFORM=vercel.');
  } else {
    redisEnabled = await yesNo(rl, 'Enable Redis (cache, rate limit, queues)?', true);
    if (redisEnabled) redisUrl = await question(rl, 'REDIS_URL', redisUrl);
    searchEnabled = await yesNo(rl, 'Enable Elasticsearch?', false);
    if (searchEnabled) esUrl = await question(rl, 'ELASTICSEARCH_URL', 'http://127.0.0.1:9200');
  }

  const jwtSecret = await question(rl, 'JWT_SECRET', 'dev_secret_change_me');
  const corsOrigin = await question(rl, 'CORS_ORIGIN', isVercel ? 'https://jobs.devminds.net' : '*');
  const seed = await yesNo(rl, 'Run database seed after migrate?', true);
  rl.close();

  return {
    hosting,
    dbProvider,
    databaseUrl,
    sqliteUrl,
    redisEnabled,
    redisUrl,
    searchEnabled,
    esUrl,
    jwtSecret,
    corsOrigin,
    seed,
  };
}

function backendEnvFrom(cfg) {
  const env = {
    HOSTING_PLATFORM: cfg.hosting,
    PORT: '4000',
    NODE_ENV: cfg.hosting === 'vercel' ? 'production' : 'development',
    DB_PROVIDER: cfg.dbProvider,
    DATABASE_URL: cfg.databaseUrl || '',
    SQLITE_URL: cfg.sqliteUrl || 'file:./dev.db',
    REDIS_ENABLED: cfg.redisEnabled ? 'true' : 'false',
    REDIS_URL: cfg.redisUrl || 'redis://127.0.0.1:6379',
    SEARCH_ENABLED: cfg.searchEnabled ? 'true' : 'false',
    SOCKET_IO_ENABLED: cfg.hosting === 'vercel' ? 'false' : 'true',
    JWT_SECRET: cfg.jwtSecret || 'dev_secret_change_me',
    JWT_EXPIRES_IN: '7d',
    CORS_ORIGIN: cfg.corsOrigin || '*',
    JSON_LIMIT: '100kb',
    URLENCODED_LIMIT: '100kb',
    PROFILE_UPLOAD_LIMIT_BYTES: '5242880',
    FILE_UPLOAD_LIMIT_BYTES: '5242880',
    SERVICE_UPLOAD_LIMIT_BYTES: '10485760',
    RATE_LIMIT_POINTS: '100',
    RATE_LIMIT_DURATION: '60',
    LOGIN_RATE_LIMIT_POINTS: '5',
    LOGIN_RATE_LIMIT_DURATION: '900',
    QUEUE_PREFIX: 'job-portal',
    ADMIN_EMAIL: 'admin@example.com',
    ADMIN_PASSWORD: 'password123',
    CRON_SECRET: '',
  };
  if (cfg.esUrl) env.ELASTICSEARCH_URL = cfg.esUrl;
  return env;
}

function frontendEnvFrom(cfg) {
  const apiBase = cfg.hosting === 'vercel'
    ? 'https://jobs.devminds.net/backend'
    : 'http://localhost:4000';
  const env = {
    NEXT_PUBLIC_SITE_URL: 'https://jobs.devminds.net',
    NEXT_PUBLIC_API_BASE: apiBase,
    NEXT_PUBLIC_API_HOST: cfg.hosting === 'vercel' ? 'https://jobs.devminds.net' : 'http://localhost:4000',
    NEXT_PUBLIC_SOCKET_IO_ENABLED: cfg.hosting === 'vercel' ? 'false' : 'true',
    NEXT_PUBLIC_DEBUG_HTTP: 'false',
    DEBUG_HTTP: 'false',
    BACKEND_VERCEL_URL: '',
    PORT: '3000',
  };
  if (cfg.searchEnabled && cfg.esUrl) {
    env.ELASTICSEARCH_NODE = cfg.esUrl;
    env.ELASTICSEARCH_URL = cfg.esUrl;
    env.SEARCH_ENABLED = 'true';
  }
  return env;
}

function writeLock(cfg) {
  fs.writeFileSync(lockPath, `${JSON.stringify({
    createdAt: new Date().toISOString(),
    hosting: cfg.hosting,
    dbProvider: cfg.dbProvider,
    redisEnabled: Boolean(cfg.redisEnabled),
    searchEnabled: Boolean(cfg.searchEnabled),
  }, null, 2)}\n`, 'utf8');
}

function cfgFromEnv(env) {
  return {
    hosting: env.HOSTING_PLATFORM || 'local',
    dbProvider: env.DB_PROVIDER || 'mysql',
    databaseUrl: env.DATABASE_URL || '',
    sqliteUrl: env.SQLITE_URL || 'file:./dev.db',
    redisEnabled: env.REDIS_ENABLED !== 'false' && env.HOSTING_PLATFORM !== 'vercel',
    redisUrl: env.REDIS_URL || 'redis://127.0.0.1:6379',
    searchEnabled: env.SEARCH_ENABLED === 'true' && Boolean(env.ELASTICSEARCH_URL),
    esUrl: env.ELASTICSEARCH_URL || '',
    jwtSecret: env.JWT_SECRET || 'dev_secret_change_me',
    corsOrigin: env.CORS_ORIGIN || '*',
    seed: false,
  };
}

async function prismaSetup(envValues, seed) {
  applyEnv(envValues);
  const childEnv = { ...process.env, ...envValues };
  console.log(`\nGenerating Prisma client (${envValues.DB_PROVIDER})...`);
  await run('npx', ['prisma', 'generate'], { env: childEnv });
  console.log('Applying migrations...');
  await run('npx', ['prisma', 'migrate', 'deploy'], { env: childEnv });
  if (seed) {
    console.log('Seeding database...');
    try {
      await run('npx', ['prisma', 'db', 'seed'], { env: childEnv });
    } catch (err) {
      console.warn('Seed failed (continuing):', err.message);
    }
  }
}

function startProcess(label, cmd, args, cwd, env) {
  console.log(`Starting ${label}...`);
  const child = spawn(cmd, args, { stdio: 'inherit', shell: true, cwd, env });
  child.on('exit', (code) => {
    if (code && code !== 0) console.error(`${label} exited with code ${code}`);
  });
  return child;
}

async function main() {
  const opts = parseArgs();
  const frontendRoot = defaultFrontendPath();
  const hasEnv = fs.existsSync(envPath);
  const hasLock = fs.existsSync(lockPath);
  const shouldWizard = opts.reset || (!hasLock && !hasEnv);

  let cfg;
  let backendEnv;
  if (shouldWizard) {
    if (opts.defaults) {
      cfg = defaultCfg();
      console.log('Using defaults: local SQLite, Redis off, Elasticsearch off');
    } else {
      cfg = await wizard();
    }
    backendEnv = backendEnvFrom(cfg);
    writeEnvFile(envPath, backendEnv);
    writeLock(cfg);
    if (fs.existsSync(path.join(frontendRoot, 'package.json'))) {
      writeEnvFile(path.join(frontendRoot, '.env'), frontendEnvFrom(cfg));
      console.log(`Wrote frontend env: ${path.join(frontendRoot, '.env')}`);
    } else {
      console.warn(`Frontend not found at ${frontendRoot}. Set FRONTEND_PATH to write its .env.`);
    }
    await prismaSetup(backendEnv, cfg.seed);
  } else {
    backendEnv = loadDotEnv(envPath);
    cfg = cfgFromEnv(backendEnv);
    if (!hasLock) writeLock(cfg);
    applyEnv(backendEnv);
    console.log(`Using existing stack: DB=${cfg.dbProvider} hosting=${cfg.hosting}`);
  }

  if (opts.setupOnly) {
    console.log('Setup complete.');
    return;
  }

  const children = [];
  children.push(startProcess('API', 'npm', ['run', 'dev'], backendRoot, { ...process.env, ...backendEnv }));
  if (fs.existsSync(path.join(frontendRoot, 'package.json'))) {
    const feEnv = {
      ...process.env,
      ...loadDotEnv(path.join(frontendRoot, '.env')),
      PORT: process.env.FRONTEND_PORT || '3000',
    };
    children.push(startProcess('frontend', 'npm', ['run', 'dev'], frontendRoot, feEnv));
  }

  const shutdown = () => {
    for (const child of children) {
      try { child.kill('SIGINT'); } catch { /* ignore */ }
    }
    process.exit(0);
  };
  process.on('SIGINT', shutdown);
  process.on('SIGTERM', shutdown);
}

main().catch((err) => {
  console.error(err.message || err);
  process.exit(1);
});
